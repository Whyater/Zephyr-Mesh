"""Independent checks for estimation, sensor and control code.

Every test here compares the code against something that was NOT derived
from the code under test: a closed-form result from a textbook, a separate
library routine (numpy.polyfit), or truth generated by a different method
than the filter's own model. Each test says in a comment which fact it uses.
"""
from __future__ import annotations

import numpy as np
import pytest

from sim.controller import GeometricFlightController
